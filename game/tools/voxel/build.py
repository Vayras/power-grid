"""Build the voxel sprite atlas: renders every model in models.py and writes
web/atlas.png, web/sprites.json and src/sprites.rs (same format and order as the old tools/build_atlas.py,
plus TRUCK at the end).

The atlas is drawn at 2x the game's base tile (128x64 px per tile). Every rect, anchor and emitter is even,
so the renderer can make the 1x atlas with a plain 2x2 box filter.

    tools/voxel/.venv/bin/python tools/voxel/build.py [--sheet out.png] [--only NAME,...]
"""
import os, sys, json, time
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from PIL import Image
import vox, models

ROOT = os.path.dirname(os.path.dirname(HERE))
ACC_SHARE = [0.0, 0.16, 0.12, 0.14, 0.30, 0.16]   # share of accent patches per site (Texas has none)


def main():
    args = sys.argv[1:]
    sheet = args[args.index('--sheet') + 1] if '--sheet' in args else None
    only = set(args[args.index('--only') + 1].split(',')) if '--only' in args else None
    out = []
    t0 = time.time()
    for name, m, kind in models.all_sprites():
        if only and name not in only: continue
        r = vox.render(m, solid=(kind == 'ground'))
        im, ax, ay, em = r
        if kind in ('tree', 'point'):
            ay -= 32           # anchored at the tile centre instead of its top corner
            em = [(x, y - 32) for x, y in em]
        out.append((name, im, ax, ay, em))
        print(f'{name:14s} {im.width:4d}x{im.height:<4d} ax={ax:5d} ay={ay:5d} emit={len(em)}  {time.time() - t0:5.1f}s', flush=True)
    if sheet:
        contact(out, sheet)
    if only: return
    write(out)


def contact(out, path):
    cols = 8; cw, ch = 280, 300
    rows = (len(out) + cols - 1) // cols
    sh = Image.new('RGBA', (cols * cw, rows * ch), (233, 231, 225, 255))
    from PIL import ImageDraw
    d = ImageDraw.Draw(sh)
    for k, (name, im, ax, ay, em) in enumerate(out):
        x, y = (k % cols) * cw, (k // cols) * ch
        s = min(1.0, (cw - 10) / im.width, (ch - 30) / im.height)
        im2 = im.resize((max(1, int(im.width * s)), max(1, int(im.height * s))), Image.LANCZOS) if s < 1 else im
        sh.alpha_composite(im2, (x + (cw - im2.width) // 2, y + ch - 24 - im2.height))
        d.text((x + 6, y + ch - 18), name, fill=(40, 40, 40, 255))
    sh.save(path)
    print('sheet', path)


def write(out):
    W = 2048
    order = sorted(range(len(out)), key=lambda k: -out[k][1].height)
    x = y = rowh = 0
    rects = {}
    for k in order:
        name, im, ax, ay, em = out[k]
        w, h = im.width + im.width % 2, im.height + im.height % 2
        if x + w + 2 > W:
            x = 0; y += rowh + 2; rowh = 0
        rects[name] = (x, y, w, h, ax, ay, em)
        x += w + 2; rowh = max(rowh, h)
    H = y + rowh + 2
    H += H % 2
    atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    for name, im, ax, ay, em in out:
        r = rects[name]
        atlas.alpha_composite(im, (r[0], r[1]))
    atlas.save(f'{ROOT}/web/atlas.png', optimize=True)

    names = [o[0] for o in out]
    lines = ['// Generated by tools/voxel/build.py. Do not edit.',
             '// Atlas at 2x the base tile (128x64 px per tile); every rect, anchor and emitter is even so the',
             '// renderer can box-filter a 1x copy. Anchors are relative to the top corner of the origin tile',
             '// (trees and workers: the tile centre). `top` is the y of the topmost solid pixel, relative to the anchor.',
             f'pub const ATLAS_W: usize = {W};', f'pub const ATLAS_H: usize = {H};',
             '#[derive(Clone, Copy)]',
             'pub struct Spr { pub x: u16, pub y: u16, pub w: u16, pub h: u16, pub ax: i16, pub ay: i16, pub e0: u8, pub ne: u8, pub top: i16 }']
    emit_all, spr_lines = [], []
    for k, n in enumerate(names):
        r = rects[n]
        e0 = len(emit_all); emit_all += [(ex - ex % 2, ey - ey % 2) for ex, ey in r[6]]
        a = out[names.index(n)][1].getchannel('A').point(lambda v: 255 if v > 200 else 0).getbbox()
        top = r[5] + (a[1] if a else 0); top -= top % 2
        spr_lines.append(f'    Spr {{ x: {r[0]}, y: {r[1]}, w: {r[2]}, h: {r[3]}, ax: {r[4]}, ay: {r[5]}, e0: {e0}, ne: {len(r[6])}, top: {top} }}, // {k} {n}')
        lines.append(f'pub const {n}: usize = {k};')
    lines.append('pub const N_TREES: usize = 11;')
    lines.append('pub const G_SITE_VAR: usize = 4; pub const G_SITE_ACC: usize = 3; pub const G_SITE_ROUGH: usize = 2;')
    lines.append('pub const G_SITE_N: usize = 9;')
    lines.append('pub const G_SITE_ACC_SHARE: [f32; 6] = [' + ', '.join(f'{v:.2}' if v else '0.0' for v in ACC_SHARE) + '];')
    lines.append('pub static SPRITES: [Spr; %d] = [' % len(names))
    lines += spr_lines
    lines.append('];')
    lines.append('pub static EMIT: [(i16, i16); %d] = [%s];' % (len(emit_all), ', '.join(f'({a}, {b})' for a, b in emit_all)))
    open(f'{ROOT}/src/sprites.rs', 'w').write('\n'.join(lines) + '\n')
    def solid(n):   # bounding box of the solid pixels (the baked ground shadow is at most ~42% alpha)
        bb = out[names.index(n)][1].getchannel('A').point(lambda v: 255 if v > 150 else 0).getbbox() or (0, 0, rects[n][2], rects[n][3])
        return [bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]]
    json.dump({n: list(rects[n][:4]) + solid(n) for n in names}, open(f'{ROOT}/web/sprites.json', 'w'))
    sz = os.path.getsize(f'{ROOT}/web/atlas.png')
    print('atlas', W, H, 'sprites', len(names), 'emitters', len(emit_all), f'{sz / 1024:.0f} KB')


if __name__ == '__main__':
    main()
